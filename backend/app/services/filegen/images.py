"""Generated images: validated, re-encoded without metadata, marked as AI-generated, and made embeddable.

Pure (Pillow only, no `app` imports). The bytes come from an image model, so they're decoded only in the filegen
child process (child.py, kind "image"), never in the backend: PNG, JPEG and WebP only, sizes checked before
decoding, the first frame only.
"""

import io
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Literal
from xml.sax.saxutils import escape

from PIL import Image, ImageOps, PngImagePlugin

from . import ImageRef, RenderError, xml_safe

ImageFormat = Literal["png", "jpeg", "webp"]
# format -> (Pillow's name, extension, content type)
IMAGE_FORMATS: dict[str, tuple[str, str, str]] = {
    "png": ("PNG", ".png", "image/png"),
    "jpeg": ("JPEG", ".jpg", "image/jpeg"),
    "webp": ("WEBP", ".webp", "image/webp"),
}
MAX_IMAGE_BYTES = 32 * 1024 * 1024
MAX_PIXELS = 16_777_216
MIN_EDGE, MAX_EDGE = 16, 4096
PREVIEW_EDGE, PREVIEW_QUALITY = 1024, 82
THUMB_EDGE, THUMB_QUALITY = 256, 75
QUALITY = 90  # re-encoded JPEG and WebP
EMBED_EDGE, EMBED_QUALITY = 2000, 88
MAX_CREATOR_CHARS = 200

_OPEN_FORMATS = ["PNG", "JPEG", "WEBP"]
# Pillow reports a JPEG with a multi-picture index (MPO) under its own name; only its first picture is read.
_FORMAT_NAMES: dict[str, ImageFormat] = {"PNG": "png", "JPEG": "jpeg", "MPO": "jpeg", "WEBP": "webp"}
_WHITE = (255, 255, 255)
_SAFE_NAME = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]{0,99}")
_TOO_BIG = "The image model returned an image larger than 32 MB, which this app doesn't accept."
_NOT_AN_IMAGE = "The image model returned data that isn't a PNG, JPEG or WebP image."


class ImageError(RenderError):
    """The image can't be used. str() is safe for the model."""


@dataclass(frozen=True)
class NormalizedImage:
    format: ImageFormat
    width: int
    height: int


def normalize(source: Path, out_dir: Path, *, creator: str) -> NormalizedImage:
    """Validates `source` and writes out_dir/image.<ext> (same format, no source metadata, an XMP packet marking it
    as AI-generated by `creator`), out_dir/preview.webp (long edge 1024) and out_dir/thumb.webp (256)."""
    image, fmt = _decode(source)
    image = _clean(image.convert("RGBA" if image.has_transparency_data else "RGB"))
    pillow_name, extension, _ = IMAGE_FORMATS[fmt]
    xmp = _xmp(creator)
    target = out_dir / f"image{extension}"
    if fmt == "png":
        info = PngImagePlugin.PngInfo()
        info.add_itxt("XML:com.adobe.xmp", xmp)  # Pillow 12.3 ignores xmp= for PNG
        image.save(target, pillow_name, compress_level=6, pnginfo=info)
    elif fmt == "jpeg":
        image = _flattened(image)
        image.save(target, pillow_name, quality=QUALITY, xmp=xmp.encode())
    else:
        image.save(target, pillow_name, quality=QUALITY, method=4, xmp=xmp.encode())
    for name, edge, quality in (
        ("preview.webp", PREVIEW_EDGE, PREVIEW_QUALITY),
        ("thumb.webp", THUMB_EDGE, THUMB_QUALITY),
    ):
        _shrunk(image, edge).save(out_dir / name, "WEBP", quality=quality, method=4)
    return NormalizedImage(fmt, image.width, image.height)


def embeddable_jpeg(path: Path, max_edge: int = EMBED_EDGE) -> tuple[bytes, int, int]:
    """(JPEG bytes, width, height) for a PDF or DOCX: transparency flattened on white, the long edge at most
    `max_edge` (never enlarged), no metadata. python-docx can't read WebP, so both renderers get JPEG."""
    image, _ = _decode(path)
    image = _flattened(_shrunk(image, max_edge))
    buffer = io.BytesIO()
    image.save(buffer, "JPEG", quality=EMBED_QUALITY)
    return buffer.getvalue(), image.width, image.height


def load_embeddable(ref: ImageRef) -> tuple[bytes, int, int]:
    """The JPEG of a figure's image from the render work directory (the child's working directory). The path must
    be a bare file name the server copied in: separators, "..", absolute paths and links are refused."""
    name = ref.path
    if not _SAFE_NAME.fullmatch(name) or ".." in name:
        raise ImageError("The image's file name isn't a plain name in the work directory.")
    path = Path(name)
    if path.is_symlink() or not path.is_file():
        raise ImageError("The image's file is missing.")
    return embeddable_jpeg(path)


class Embedder:
    """Each figure's image, loaded once per file; failures leave the figure as a text reference."""

    def __init__(self) -> None:
        self._loaded: dict[int, tuple[bytes, int, int] | None] = {}
        self.embedded = 0
        self.failed = 0

    def peek(self, ref: ImageRef) -> tuple[bytes, int, int] | None:
        """The image (or None when it can't be read) without counting it: for laying out what comes before it."""
        if ref.id not in self._loaded:
            try:
                self._loaded[ref.id] = load_embeddable(ref)
            except (ImageError, OSError):
                self._loaded[ref.id] = None
        return self._loaded[ref.id]

    def load(self, ref: ImageRef) -> tuple[bytes, int, int] | None:
        """The image of a figure being drawn, counted for notes()."""
        loaded = self.peek(ref)
        if loaded is None:
            self.failed += 1
        else:
            self.embedded += 1
        return loaded

    def notes(self) -> list[str]:
        notes = []
        if self.embedded:
            notes.append(f"Embedded {self.embedded} image{'s' if self.embedded != 1 else ''}.")
        if self.failed == 1:
            notes.append("1 image couldn't be read, so the file has a text reference to it instead.")
        elif self.failed:
            notes.append(f"{self.failed} images couldn't be read, so the file has text references to them instead.")
        return notes


def _decode(source: Path) -> tuple[Image.Image, ImageFormat]:
    """The first frame, upright and loaded, after the size checks."""
    if source.stat().st_size > MAX_IMAGE_BYTES:
        raise ImageError(_TOO_BIG)
    # Pillow refuses twice this many pixels when it reads the header. Set here rather than on import, so a process
    # that only imports this module for its constants keeps its own limit.
    Image.MAX_IMAGE_PIXELS = MAX_PIXELS
    try:
        opened = Image.open(source, formats=_OPEN_FORMATS)
    except MemoryError:
        raise
    except Exception as exc:  # unknown formats, DecompressionBombError, broken headers
        raise ImageError(_NOT_AN_IMAGE) from exc
    with opened:
        fmt = _FORMAT_NAMES.get(opened.format or "")
        if fmt is None:
            raise ImageError(_NOT_AN_IMAGE)
        width, height = opened.size
        if width > MAX_EDGE or height > MAX_EDGE or width * height > MAX_PIXELS:
            raise ImageError(f"The image is {width}×{height} pixels, larger than this app accepts.")
        if width < MIN_EDGE or height < MIN_EDGE:
            raise ImageError(f"The image is {width}×{height} pixels, smaller than this app accepts.")
        try:
            opened.seek(0)
            image = ImageOps.exif_transpose(opened)  # a loaded copy
            image.load()
        except MemoryError:
            raise
        except Exception as exc:  # truncated or corrupt data
            raise ImageError(_NOT_AN_IMAGE) from exc
    return image, fmt


def _clean(image: Image.Image) -> Image.Image:
    """Without the source's metadata: Pillow writes some of `info` back (a JPEG comment, for one)."""
    image.info = {}
    return image


def _flattened(image: Image.Image) -> Image.Image:
    """RGB, transparent areas on white."""
    if image.mode == "RGB":
        return image
    rgba = image.convert("RGBA")
    background = Image.new("RGB", rgba.size, _WHITE)
    background.paste(rgba, mask=rgba.getchannel("A"))
    return background


def _shrunk(image: Image.Image, edge: int) -> Image.Image:
    """A copy with the long edge at most `edge`, never enlarged."""
    copy = image.copy()
    copy.thumbnail((edge, edge), Image.Resampling.LANCZOS)
    copy.info = {}
    return copy


def _xmp(creator: str) -> str:
    """One XMP packet: IPTC's digital source type "trained algorithmic media" and the image model as creator tool."""
    tool = escape(xml_safe(creator)[:MAX_CREATOR_CHARS], {'"': "&quot;"})
    return (
        '<?xpacket begin="﻿" id="W5M0MpCehiHzreSzNTczkc9d"?>'
        '<x:xmpmeta xmlns:x="adobe:ns:meta/">'
        '<rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">'
        '<rdf:Description rdf:about="" xmlns:Iptc4xmpExt="http://iptc.org/std/Iptc4xmpExt/2008-02-29/" '
        'xmlns:xmp="http://ns.adobe.com/xap/1.0/" '
        'Iptc4xmpExt:DigitalSourceType="http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia" '
        f'xmp:CreatorTool="{tool}"/>'
        "</rdf:RDF></x:xmpmeta>"
        '<?xpacket end="w"?>'
    )
